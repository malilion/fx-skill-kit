// SSD1306 vertical pages. A set bit is straight alpha >= 128. RGB is ignored.
export function packAlphaMask(frames, w, h) {
  if (!Number.isInteger(w) || !Number.isInteger(h) || w < 1 || h < 1 || !frames?.length) {
    throw new Error('Alpha mask needs frames and positive dimensions');
  }
  const stride = w * Math.ceil(h / 8);
  const data = new Uint8Array(stride * frames.length);
  frames.forEach((frame, fi) => {
    const pixels = frame.data ?? frame;
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (pixels[(y * w + x) * 4 + 3] >= 128) data[fi * stride + Math.floor(y / 8) * w + x] |= 1 << (y % 8);
    }
  });
  return data;
}

export function formatCHeader({ id, w, h, frames, dt, seed }) {
  const data = packAlphaMask(frames, w, h);
  const symbol = `FX_${String(id).replaceAll(/[^a-z0-9]/gi, '_').toUpperCase()}`;
  const stride = data.length / frames.length;
  const rows = Array.from({ length: Math.ceil(data.length / 16) }, (_, i) => {
    const hex = Array.from(data.subarray(i * 16, (i + 1) * 16), b => `0x${b.toString(16).padStart(2, '0')}`);
    return `  ${hex.join(', ')},`;
  });
  return `// Generated by fx-skill-kit: uncompressed 1-bit alpha mask, vertical pages, seed=${seed}\n#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n#define ${symbol}_W ${w}\n#define ${symbol}_H ${h}\n#define ${symbol}_FRAMES ${frames.length}\n#define ${symbol}_FRAME_BYTES ${stride}\n#define ${symbol}_FRAME_MS ${(dt * 1000).toFixed(6)}\nstatic const uint8_t ${symbol}_DATA[] PROGMEM = {\n${rows.join('\n')}\n};\n`;
}

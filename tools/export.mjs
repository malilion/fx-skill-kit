import { mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { loadFX, sampleFX, withoutMathRandom } from '../src/core/run.js';
import { renderFX } from './render.mjs';

export async function exportAsset(file, targetFormat, { outDir, seed = 42, palette } = {}) {
  if (!['sheet', 'gif', 'png', 'c-header'].includes(targetFormat)) throw new Error('target_format must be sheet, gif, png, or c-header');
  if (targetFormat !== 'c-header') {
    const result = await renderFX(file, { outDir, seed, palette, sheet: targetFormat === 'sheet', gif: targetFormat === 'gif' });
    return { format: targetFormat, files: targetFormat === 'sheet' ? [result.sprite.png, result.sprite.json] : [targetFormat === 'gif' ? result.gif : result.png] };
  }
  const run = await withoutMathRandom(async () => sampleFX(await loadFX(file), { seed, effectOptions: { palette } }));
  const { w, h, id, loop } = run.meta;
  const frames = loop ? run.frames.slice(0, -1) : run.frames;
  // Page-packed vertical bits: SSD1306 native order, alpha >=128 is a lit pixel.
  const stride = w * Math.ceil(h / 8);
  const data = new Uint8Array(stride * frames.length);
  frames.forEach((frame, fi) => {
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      if (frame.data[(y * w + x) * 4 + 3] >= 128) data[fi * stride + Math.floor(y / 8) * w + x] |= 1 << (y % 8);
    }
  });
  const symbol = `FX_${id.replaceAll(/[^a-z0-9]/g, '_').toUpperCase()}`;
  const rows = Array.from({ length: Math.ceil(data.length / 16) }, (_, i) => `  ${Array.from(data.subarray(i * 16, (i + 1) * 16), b => `0x${b.toString(16).padStart(2, '0')}`).join(', ')},`);
  const header = `// Generated by fx-skill-kit: uncompressed 1-bit alpha mask, vertical pages, seed=${seed}\n#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n#endif\n#define ${symbol}_W ${w}\n#define ${symbol}_H ${h}\n#define ${symbol}_FRAMES ${frames.length}\n#define ${symbol}_FRAME_BYTES ${stride}\n#define ${symbol}_FRAME_MS ${(run.dt * 1000).toFixed(6)}\nstatic const uint8_t ${symbol}_DATA[] PROGMEM = {\n${rows.join('\n')}\n};\n`;
  const directory = resolve(outDir ?? join('records', id));
  await mkdir(directory, { recursive: true });
  const filePath = join(directory, 'asset.h');
  await writeFile(filePath, header);
  return { format: targetFormat, files: [filePath], bytes: data.length, frames: frames.length, width: w, height: h };
}
